"""Хранилище сборщика atm_monitor — схема `atm_monitor` в общей базе PostgreSQL.

Отдельная схема, потому что в public уже есть своя таблица atms (реестр банка).
Соединения открываются с search_path=atm_monitor, поэтому SQL сборщика пишет
имена таблиц без префикса."""
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from .config import settings

SCHEMA_NAME = "atm_monitor"

SCHEMA = """
CREATE SCHEMA IF NOT EXISTS atm_monitor;

CREATE TABLE IF NOT EXISTS atm_monitor.atms (
    id BIGINT PRIMARY KEY,
    serial TEXT, tid TEXT, client_id BIGINT,
    model_id BIGINT, model_name TEXT, vendor_name TEXT, variant_name TEXT, type_name TEXT,
    hw_uid TEXT, atm_uid TEXT,
    branch_number TEXT, mfo TEXT, merchant_id TEXT, terminal_id TEXT, host_provider TEXT,
    country_id BIGINT, region_id BIGINT, city_id BIGINT,
    address TEXT, place TEXT, latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
    timezone_offset INTEGER,
    max_cashout BIGINT, max_cashin BIGINT,
    status TEXT,
    api_created_at TIMESTAMPTZ, api_updated_at TIMESTAMPTZ,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_atms_tid ON atm_monitor.atms(tid);

CREATE TABLE IF NOT EXISTS atm_monitor.poll_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL, finished_at TIMESTAMPTZ,
    status TEXT, atm_count INTEGER, error_message TEXT
);

CREATE TABLE IF NOT EXISTS atm_monitor.atm_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    poll_run_id BIGINT REFERENCES atm_monitor.poll_runs(id),
    polled_at TIMESTAMPTZ NOT NULL,
    agent_status TEXT, agent_last_online TIMESTAMPTZ,
    service_status TEXT, app_status TEXT, app_conn_status TEXT,
    sup_switch_status TEXT, platform_status TEXT, vdm_status TEXT, state_updated_at TIMESTAMPTZ,
    last_transaction_last TIMESTAMPTZ, last_transaction_cash_out TIMESTAMPTZ,
    last_transaction_cash_in TIMESTAMPTZ, last_transaction_other TIMESTAMPTZ,
    cdm_total_uzs DOUBLE PRECISION, cdm_total_usd DOUBLE PRECISION, cdm_total_eur DOUBLE PRECISION,
    dispenser_status TEXT, acceptor_status TEXT, epp_status TEXT, card_reader_status TEXT,
    contactless_status TEXT, printer_status TEXT, jprinter_status TEXT, barcode_reader_status TEXT,
    raw_json JSONB
);
CREATE INDEX IF NOT EXISTS ix_snap_atm_time ON atm_monitor.atm_snapshots(atm_id, polled_at);

CREATE TABLE IF NOT EXISTS atm_monitor.cassette_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atm_snapshot_id BIGINT REFERENCES atm_monitor.atm_snapshots(id),
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    polled_at TIMESTAMPTZ NOT NULL,
    cassette_index INTEGER, unit_id TEXT, cassette_type TEXT, status TEXT,
    count INTEGER, currency TEXT, nominal BIGINT
);
CREATE INDEX IF NOT EXISTS ix_cass_snapshot ON atm_monitor.cassette_snapshots(atm_snapshot_id);

CREATE TABLE IF NOT EXISTS atm_monitor.turnover_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    polled_at TIMESTAMPTZ NOT NULL,
    device TEXT, currency TEXT, balance DOUBLE PRECISION,
    dispense_amount_rate DOUBLE PRECISION, present_amount_rate DOUBLE PRECISION,
    forecast_hours DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS ix_turn_atm_time ON atm_monitor.turnover_snapshots(atm_id, polled_at);

-- Прогноз снятий (atm_monitor/forecast.py): один прогон в сутки.
CREATE TABLE IF NOT EXISTS atm_monitor.forecast_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL, finished_at TIMESTAMPTZ,
    status TEXT, model TEXT, horizon_days INTEGER,
    train_rows INTEGER, atm_count INTEGER,
    metrics JSONB, error_message TEXT
);

CREATE TABLE IF NOT EXISTS atm_monitor.atm_forecast_summary (
    run_id BIGINT NOT NULL REFERENCES atm_monitor.forecast_runs(id) ON DELETE CASCADE,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    method TEXT,
    history_days INTEGER,
    balance_uzs DOUBLE PRECISION,
    withdrawal_24h DOUBLE PRECISION,
    withdrawal_horizon DOUBLE PRECISION,
    low_cash_at TIMESTAMPTZ,
    cashout_at TIMESTAMPTZ,
    refill_uzs DOUBLE PRECISION,
    PRIMARY KEY (run_id, atm_id)
);

-- ── История (atm_monitor/history.py) ─────────────────────────────
-- Доступный остаток (без неисправных/отсутствующих кассет) и сумма последней
-- загрузки по BTech (cdmInitialAmount) — считаются из снимка при обработке истории.
ALTER TABLE atm_monitor.atm_snapshots ADD COLUMN IF NOT EXISTS cdm_available_uzs DOUBLE PRECISION;
ALTER TABLE atm_monitor.atm_snapshots ADD COLUMN IF NOT EXISTS cdm_initial_uzs DOUBLE PRECISION;
-- Снимки пишутся по времени — BRIN по polled_at крошечный и быстрый для выборок за период.
CREATE INDEX IF NOT EXISTS brin_snap_polled ON atm_monitor.atm_snapshots USING brin (polled_at);
CREATE INDEX IF NOT EXISTS ix_turn_atm_id ON atm_monitor.turnover_snapshots(atm_id, id);

-- Изменения состояния: только переходы (онлайн → офлайн, кассета OK → INOP,
-- начало/конец «нет денег»), а не одно и то же каждый опрос.
CREATE TABLE IF NOT EXISTS atm_monitor.atm_state_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    at TIMESTAMPTZ NOT NULL,
    kind TEXT NOT NULL,          -- agent / service / device:<name> / cassette:<index> / cash
    old_value TEXT, new_value TEXT,
    snapshot_id BIGINT
);
CREATE INDEX IF NOT EXISTS ix_events_atm_at ON atm_monitor.atm_state_events(atm_id, at);
CREATE INDEX IF NOT EXISTS ix_events_kind_at ON atm_monitor.atm_state_events(kind, at);

-- Фактические инкассации (загрузки), найденные по данным BTech.
CREATE TABLE IF NOT EXISTS atm_monitor.atm_incassations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    at TIMESTAMPTZ NOT NULL,
    snapshot_id BIGINT NOT NULL UNIQUE,
    before_snapshot_id BIGINT,
    balance_before DOUBLE PRECISION, available_before DOUBLE PRECISION,
    balance_after DOUBLE PRECISION, available_after DOUBLE PRECISION,
    initial_uzs DOUBLE PRECISION,           -- cdmInitialAmount после загрузки (как отдаёт BTech)
    method TEXT NOT NULL,                   -- initial_amount / balance_jump
    notes_after JSONB NOT NULL DEFAULT '{}',-- номинал → купюр после загрузки
    recommendation_id BIGINT,               -- рекомендация системы, действовавшая на момент загрузки
    followed_plan BOOLEAN NOT NULL DEFAULT FALSE  -- выполнена по принятому плану системы
);
CREATE INDEX IF NOT EXISTS ix_inc_atm_at ON atm_monitor.atm_incassations(atm_id, at);

-- Суточные итоги по банкомату (местная дата TIMEZONE) — страницы не пересчитывают сырые снимки.
CREATE TABLE IF NOT EXISTS atm_monitor.atm_daily (
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    day DATE NOT NULL,
    withdrawn DOUBLE PRECISION NOT NULL DEFAULT 0,
    covered_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    avg_balance DOUBLE PRECISION, avg_available DOUBLE PRECISION, min_available DOUBLE PRECISION,
    cashout_hours DOUBLE PRECISION NOT NULL DEFAULT 0,  -- часы онлайн с нулевым доступным остатком
    offline_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    samples INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (atm_id, day)
);
CREATE INDEX IF NOT EXISTS ix_daily_day ON atm_monitor.atm_daily(day);

-- Рекомендации системы: журнал, строки не меняются (кроме статуса принятия) —
-- с ними честно сравниваются фактические загрузки.
CREATE TABLE IF NOT EXISTS atm_monitor.recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    created_at TIMESTAMPTZ NOT NULL,
    snapshot_id BIGINT,
    forecast_run_id BIGINT,
    method TEXT,                         -- метод прогноза спроса: xgboost / mean_7d / btech / history
    available_uzs DOUBLE PRECISION,
    capacity_uzs DOUBLE PRECISION,
    demand_per_day DOUBLE PRECISION,
    hours_to_empty DOUBLE PRECISION,
    due_at TIMESTAMPTZ,                  -- крайний срок инкассации (до достижения страхового запаса)
    cycle_days DOUBLE PRECISION,         -- на сколько дней рассчитана загрузка
    load_uzs DOUBLE PRECISION,           -- сколько должно быть в банкомате после загрузки
    notes JSONB NOT NULL DEFAULT '{}',   -- номинал → купюр
    score INTEGER NOT NULL,              -- срочность 1..10
    reasons JSONB NOT NULL DEFAULT '[]',
    needs_technician BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'open', -- open / accepted / done / superseded
    accepted_at TIMESTAMPTZ, accepted_by TEXT,
    superseded_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_rec_atm_created ON atm_monitor.recommendations(atm_id, created_at);
CREATE INDEX IF NOT EXISTS ix_rec_status ON atm_monitor.recommendations(status);

-- Служебные отметки обработки истории (до какого снимка обработано и т.п.).
CREATE TABLE IF NOT EXISTS atm_monitor.history_state (
    key TEXT PRIMARY KEY,
    value BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS atm_monitor.atm_forecasts (
    run_id BIGINT NOT NULL REFERENCES atm_monitor.forecast_runs(id) ON DELETE CASCADE,
    atm_id BIGINT NOT NULL REFERENCES atm_monitor.atms(id),
    forecast_date DATE NOT NULL,
    withdrawal_uzs DOUBLE PRECISION NOT NULL,
    balance_end_uzs DOUBLE PRECISION,
    PRIMARY KEY (run_id, atm_id, forecast_date)
);
"""

_pool = None


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        _pool = ConnectionPool(
            settings.DATABASE_URL,
            min_size=1,
            max_size=4,
            kwargs={"row_factory": dict_row, "options": f"-c search_path={SCHEMA_NAME} -c timezone=UTC"},
            name="atm_monitor",
            open=True,
        )
    return _pool


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def connect():
    """Соединение с БД сборщика. Коммит при успехе, rollback при ошибке."""
    with _get_pool().connection() as conn:
        yield conn


def create_schema(conn: psycopg.Connection) -> None:
    """Создаёт схему atm_monitor в переданной транзакции (вызывается из core.db.init_db)."""
    conn.execute(SCHEMA)


def init_db():
    with connect() as conn:
        create_schema(conn)
