def create_dataset_import_tables(conn) -> None:
    conn.execute("""
        CREATE TABLE IF NOT EXISTS dataset_imports (
            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind        TEXT NOT NULL,
            seq         INTEGER NOT NULL,
            filename    TEXT,
            imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            rows_count  INTEGER NOT NULL DEFAULT 0,
            date_from   DATE,
            date_to     DATE,
            UNIQUE (kind, seq)
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_dataset_imports_kind ON dataset_imports(kind, seq)")


def ensure_import_column(conn, table: str) -> None:
    conn.execute(
        f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS import_id BIGINT "
        "REFERENCES dataset_imports(id) ON DELETE CASCADE"
    )
    conn.execute(f"CREATE INDEX IF NOT EXISTS idx_{table}_import ON {table}(import_id)")


def adopt_unassigned(conn, kind: str, table: str, date_col: Optional[str] = None) -> None:
    """Bazada turgan eski qatorlar 1-import bo'lib, yangi fayldan oldin ko'rinadi."""
    pending = int(conn.execute(f"SELECT COUNT(*) AS n FROM {table} WHERE import_id IS NULL").fetchone()["n"])
    if not pending:
        return
    date_from = date_to = None
    if date_col:
        span = conn.execute(
            f"SELECT MIN({date_col}) AS d0, MAX({date_col}) AS d1 FROM {table} WHERE import_id IS NULL"
        ).fetchone()
        date_from, date_to = span["d0"], span["d1"]
    first_at = conn.execute(
        f"SELECT MIN(imported_at) AS t FROM {table} WHERE import_id IS NULL"
    ).fetchone()["t"]
    imp = start_import(conn, kind, None, pending, date_from, date_to, imported_at=first_at)
    conn.execute(f"UPDATE {table} SET import_id = %s WHERE import_id IS NULL", (imp["id"],))


def restore_original_import_time(conn, kind: str, table: str) -> None:
    """Fayl nomisiz eski yuklash bugungi vaqt bilan yozilgan bo'lsa, qatorlarning haqiqiy sanasiga qaytariladi."""
    conn.execute(
        f"""
        UPDATE dataset_imports AS d
        SET imported_at = src.first_at
        FROM (
            SELECT import_id, MIN(imported_at) AS first_at
            FROM {table}
            WHERE import_id IS NOT NULL
            GROUP BY import_id
        ) AS src
        WHERE d.id = src.import_id
          AND d.kind = %s
          AND d.filename IS NULL
          AND src.first_at IS NOT NULL
          AND d.imported_at IS DISTINCT FROM src.first_at
        """,
        (kind,),
    )


def start_import(
    conn,
    kind: str,
    filename: Optional[str],
    rows_count: int,
    date_from: Optional[date],
    date_to: Optional[date],
    imported_at: Optional[datetime] = None,
) -> Dict[str, Any]:
    seq = int(conn.execute(
        "SELECT COALESCE(MAX(seq), 0) + 1 AS n FROM dataset_imports WHERE kind = %s",
        (kind,),
    ).fetchone()["n"])
    row = conn.execute(
        """
        INSERT INTO dataset_imports (kind, seq, filename, imported_at, rows_count, date_from, date_to)
        VALUES (%s, %s, %s, COALESCE(%s, now()), %s, %s, %s)
        RETURNING id, seq, filename, imported_at, rows_count, date_from, date_to
        """,
        (kind, seq, filename, imported_at, rows_count, date_from, date_to),
    ).fetchone()
    return _public(row)


def list_dataset_imports(kind: str) -> List[Dict[str, Any]]:
    from .db import connect, ensure_schema

    ensure_schema()
    with connect() as conn:
        rows = conn.execute(
            """
            SELECT id, seq, filename, imported_at, rows_count, date_from, date_to
            FROM dataset_imports WHERE kind = %s ORDER BY seq ASC
            """,
            (kind,),
        ).fetchall()
    return [_public(r) for r in rows]


def delete_dataset_import(kind: str, import_id: int) -> bool:
    """Bitta yuklash va uning qatorlari (ON DELETE CASCADE)."""
    from .db import connect, ensure_schema

    ensure_schema()
    with connect() as conn:
        return conn.execute(
            "DELETE FROM dataset_imports WHERE id = %s AND kind = %s",
            (import_id, kind),
        ).rowcount > 0


def resolve_import(kind: str, import_id: Optional[int] = None) -> Optional[Dict[str, Any]]:
    """import_id berilmasa — oxirgi yuklash. Noto'g'ri id — None."""
    imports = list_dataset_imports(kind)
    if import_id is None:
        return imports[-1] if imports else None
    return next((item for item in imports if item["id"] == import_id), None)


def _iso(value: Any) -> Optional[str]:
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, date):
        return value.isoformat()
    return str(value)


def _public(row: Dict[str, Any]) -> Dict[str, Any]:
    seq = int(row["seq"])
    return {
        "id": int(row["id"]),
        "seq": seq,
        "label": f"{seq}-й импорт",
        "filename": row.get("filename"),
        "imported_at": _iso(row.get("imported_at")),
        "rows_count": int(row.get("rows_count") or 0),
        "date_from": _iso(row.get("date_from")),
        "date_to": _iso(row.get("date_to")),
    }
