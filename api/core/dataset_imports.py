"""Raqamlangan yuklamalar: 1-й импорт, 2-й импорт.

Kassirlar oyi bo'yicha ajratiladi. VASH operatsiyalari, filial schotlari va
kassa qoldig'i esa oddiy tartib raqami bilan saqlanadi. Yangi fayl eskisini
o'chirmaydi va unga qo'shilmaydi. Analitika oxirgi yuklashni ochadi, noto'g'ri
yuklashni ro'yxatdan o'chirish mumkin.
"""
from __future__ import annotations

from datetime import date, datetime
from typing import Any, Dict, List, Optional

KIND_VASH = "vash_operations"
