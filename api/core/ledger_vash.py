def branch_ledger_analytics(
    branch_id: Optional[str] = None,
    limit: int = 500,
    import_id: Optional[int] = None,
) -> Dict[str, Any]:
    """Tanlangan yuklashning oxirgi sanasi. Berilmasa — eng so'nggi import."""
    current = resolve_import(KIND_LEDGER, import_id)
    if import_id is not None and current is None:
        raise LookupError("Импорт не найден")
    if current is None:
        return _empty_ledger(None)
    with connect() as conn:
        latest = conn.execute(
            "SELECT MAX(oper_day) AS d FROM branch_ledger WHERE import_id = %s",
            (current["id"],),
        ).fetchone()["d"]
        if latest is None:
            return _empty_ledger(current)
        params: Dict[str, Any] = {"day": latest, "imp": current["id"], "limit": max(1, min(limit, 2000))}
        where = "oper_day = %(day)s AND import_id = %(imp)s"
        if branch_id:
            where += " AND (branch_id = %(branch)s OR ltrim(branch_id, '0') = ltrim(%(branch)s, '0'))"
            params["branch"] = branch_id
        accounts = conn.execute(
            f"""
            SELECT oper_day, coa_code, code, code_currency, acc_id, branch_id, saldo_out
            FROM branch_ledger
            WHERE {where}
            ORDER BY branch_id, code_currency, code
            LIMIT %(limit)s
            """,
            params,
        ).fetchall()
        totals = conn.execute(
            """
            SELECT branch_id, code_currency, SUM(saldo_out) AS saldo, COUNT(*) AS accounts
            FROM branch_ledger
            WHERE oper_day = %s AND import_id = %s
            GROUP BY branch_id, code_currency
            """,
            (latest, current["id"]),
        ).fetchall()
        counted = conn.execute(
            "SELECT COUNT(*) AS n, COUNT(DISTINCT branch_id) AS branches FROM branch_ledger WHERE oper_day = %s AND import_id = %s",
            (latest, current["id"]),
        ).fetchone()
    names = _branch_names()
    by_branch: Dict[str, Dict[str, Any]] = {}
    by_ccy: Dict[str, Dict[str, Any]] = {}
    total_uzs = 0.0
    for row in totals:
        code = str(row["branch_id"])
        info = names.get(code) or names.get(code.lstrip("0")) or {}
        item = by_branch.setdefault(code, {
            "branch_id": code,
            "name": info.get("name") or "",
            "region": info.get("region") or "",
            "uzs": 0.0,
            "accounts": 0,
            "currencies": [],
        })
        saldo = float(row["saldo"] or 0)
        n = int(row["accounts"] or 0)
        item["accounts"] += n
        item["currencies"].append({"code": row["code_currency"], "label": _currency_label(row["code_currency"]), "saldo": saldo})
        if is_uzs(row["code_currency"]):
            item["uzs"] += saldo
            total_uzs += saldo
        bucket = by_ccy.setdefault(str(row["code_currency"] or ""), {"code": row["code_currency"], "label": _currency_label(row["code_currency"]), "saldo": 0.0, "accounts": 0})
        bucket["saldo"] += saldo
        bucket["accounts"] += n
    branches = sorted(by_branch.values(), key=lambda b: -b["uzs"])
    return {
        "latest_day": _iso_date(latest),
        "rows": int(counted["n"] or 0),
        "branch_count": int(counted["branches"] or 0),
        "total_uzs": round(total_uzs, 2),
        "branches": branches,
        "by_currency": sorted(by_ccy.values(), key=lambda c: -abs(c["saldo"])),
        "accounts": [
            {
                "oper_day": _iso_date(r["oper_day"]),
                "coa_code": r["coa_code"],
                "code": r["code"],
                "code_currency": r["code_currency"],
                "currency_label": _currency_label(r["code_currency"]),
                "acc_id": r["acc_id"],
                "branch_id": r["branch_id"],
                "saldo_out": r["saldo_out"],
            }
            for r in accounts
        ],
        "import": current,
    }


def latest_ledger_by_branch() -> Dict[str, Dict[str, Any]]:
    """Oxirgi yuklash ichida har filialning o'z oxirgi sanasi."""
    current = resolve_import(KIND_LEDGER)
    if current is None:
        return {}
    with connect() as conn:
        rows = conn.execute(
            """
            WITH last_day AS (
                SELECT branch_id, MAX(oper_day) AS oper_day
                FROM branch_ledger
                WHERE import_id = %s
                GROUP BY branch_id
            )
            SELECT l.branch_id, l.oper_day, l.coa_code, l.code, l.code_currency, l.acc_id, l.saldo_out
            FROM branch_ledger l
            JOIN last_day d ON d.branch_id = l.branch_id AND d.oper_day = l.oper_day
            WHERE l.import_id = %s
            ORDER BY l.branch_id, l.code_currency, l.code
            """,
            (current["id"], current["id"]),
        ).fetchall()
    grouped: Dict[str, Dict[str, Any]] = {}
    for r in rows:
        code = str(r["branch_id"])
        item = grouped.get(code)
        if item is None:
            item = grouped[code] = {"oper_day": _iso_date(r["oper_day"]), "uzs": 0.0, "by_iso": {}, "lines": []}
        saldo = float(r["saldo_out"] or 0)
        ccy = str(r["code_currency"] or "").strip()
        if is_uzs(ccy):
            item["uzs"] += saldo
        else:
            item["by_iso"][ccy] = item["by_iso"].get(ccy, 0.0) + saldo
        if len(item["lines"]) < 30:
            item["lines"].append({
                "coa_code": r["coa_code"],
                "code": r["code"],
                "code_currency": ccy,
                "acc_id": r["acc_id"],
                "saldo_out": r["saldo_out"],
            })
    out: Dict[str, Dict[str, Any]] = {}
    for code, item in grouped.items():
        out[code] = item
        out.setdefault(code.lstrip("0"), item)
    return out


def apply_ledger_to_branches(branches: Iterable[Dict[str, Any]]) -> None:
    """Pulni yangi hisobotdan qo'yadi. limit_uzs / limit_usd eski importda qoladi."""
    latest = latest_ledger_by_branch()
    if not latest:
        return
    for branch in branches:
        code = str(branch.get("local_code") or "").strip()
        led = latest.get(code) or latest.get(code.lstrip("0"))
        if not led:
            continue
        cash = dict(branch.get("cash") or {})
        cash["balance_uzs"] = round(led["uzs"], 2)
        cash["balance_source"] = "ledger"
        cash["ledger_as_of"] = led["oper_day"]
        cash["ledger_lines"] = led["lines"]
        limit = cash.get("limit_uzs")
        if limit:
            cash["usage_pct"] = round(led["uzs"] / float(limit) * 100, 1)
        currencies = []
        for old in cash.get("currencies") or []:
            row = dict(old)
            iso = str(row.get("iso") or "")
            if iso in led["by_iso"]:
                row["amount"] = round(led["by_iso"][iso], 2)
            currencies.append(row)
        known = {str(c.get("iso") or "") for c in currencies}
        for iso, amount in led["by_iso"].items():
            if iso in known:
                continue
            meta = CURRENCY_META.get(iso, {})
            currencies.append({
                "iso": iso,
                "code": meta.get("code") or iso,
                "name": meta.get("name") or iso,
                "name_ru": meta.get("name_ru") or iso,
                "amount": round(amount, 2),
                "rate_uzs": None,
                "uzs_equivalent": None,
            })
        if currencies:
            cash["currencies"] = currencies
        branch["cash"] = cash


def _punkt_key(value: Any) -> str:
    """Operatsiyadagi N06003041 va xaritadagi 06003041 bitta punkt."""
    s = re.sub(r"\s+", "", str(value or "")).upper()
    if s.startswith("N"):
        s = s[1:]
    return s.lstrip("0")


