    empty = {"operations": 0, "points": [], "from": None, "to": None, "high": 0, "low": 0, "import": current}
    if current is None:
        return empty
    with connect() as conn:
        span = conn.execute(
            """
            SELECT COUNT(*) AS n, COUNT(DISTINCT obmen_punkt) AS points, MIN(op_date) AS d0, MAX(op_date) AS d1
            FROM vash_operations WHERE import_id = %s
            """,
            (current["id"],),
        ).fetchone()
        if not span["n"]:
            return empty
        grouped = conn.execute(
            """
            SELECT obmen_punkt,
                   MAX(branch) AS branch,
                   COUNT(*) AS ops,
                   COUNT(DISTINCT ci_acc) AS ci_accounts,
                   COUNT(DISTINCT co_acc) AS co_accounts,
                   MIN(op_date) AS first_date,
                   MAX(op_date) AS last_date
            FROM vash_operations
            WHERE import_id = %s
            GROUP BY obmen_punkt
            ORDER BY ops DESC, obmen_punkt
            """,
            (current["id"],),
        ).fetchall()
        from .dataset_imports import KIND_VASH_ZONES, adopt_unassigned
        adopt_unassigned(conn, KIND_VASH_ZONES, "vash_zones")
        zones_import = conn.execute(
            "SELECT id FROM dataset_imports WHERE kind = %s ORDER BY seq DESC LIMIT 1",
            (KIND_VASH_ZONES,),
        ).fetchone()
        if zones_import is None:
            zones = []
        else:
            zones = conn.execute(
                """
                SELECT id, vash_number, address, lat, lon, bxm_code, bxm_name
                FROM vash_zones WHERE import_id = %s
                """,
                (zones_import["id"],),
            ).fetchall()
    zone_by_key = {}
    for z in zones:
        zone_by_key.setdefault(_punkt_key(z["vash_number"]), z)
    counts = sorted(int(r["ops"]) for r in grouped)
    def pct(p: float) -> int:
        if not counts:
            return 0
        idx = min(len(counts) - 1, max(0, int(round((len(counts) - 1) * p))))
        return counts[idx]
    low_cut, high_cut = pct(0.25), pct(0.75)
    points = []
    high = low = 0
    for r in grouped:
        ops = int(r["ops"])
        hi, lo = counts[-1], counts[0]
        if hi == lo:
            band = "mid"
        elif ops >= (high_cut if len(counts) >= 4 else hi):
            band = "high"
        elif ops <= (low_cut if len(counts) >= 4 else lo):
            band = "low"
        else:
            band = "mid"
        high += band == "high"
        low += band == "low"
        zone = zone_by_key.get(_punkt_key(r["obmen_punkt"]))
        points.append({
            "obmen_punkt": r["obmen_punkt"],
            "branch": r["branch"],
            "ops": ops,
            "ci_accounts": int(r["ci_accounts"] or 0),
            "co_accounts": int(r["co_accounts"] or 0),
            "first_date": _iso_date(r["first_date"]),
            "last_date": _iso_date(r["last_date"]),
            "band": band,
            "on_map": bool(zone and zone.get("lat") is not None and zone.get("lon") is not None),
            "address": zone.get("address") if zone else None,
            "vash_id": zone.get("id") if zone else None,
            "vash_number": zone.get("vash_number") if zone else None,
            "lat": zone.get("lat") if zone else None,
            "lon": zone.get("lon") if zone else None,
        })
    matched_keys = {_punkt_key(p["obmen_punkt"]) for p in points}
    none = 0
    for key, zone in zone_by_key.items():
        if key in matched_keys:
            continue
        none += 1
        points.append({
            "obmen_punkt": zone.get("vash_number"),
            "branch": zone.get("bxm_code"),
            "bxm_name": zone.get("bxm_name"),
            "ops": 0,
            "ci_accounts": 0,
            "co_accounts": 0,
            "first_date": None,
            "last_date": None,
            "band": "none",
            "on_map": zone.get("lat") is not None and zone.get("lon") is not None,
            "address": zone.get("address"),
            "vash_id": zone.get("id"),
            "vash_number": zone.get("vash_number"),
            "lat": zone.get("lat"),
            "lon": zone.get("lon"),
        })
    return {
        "operations": int(span["n"]),
        "point_count": len(points) - none,
        "from": _iso_date(span["d0"]),
        "to": _iso_date(span["d1"]),
        "high": high,
        "low": low,
        "mid": len(points) - none - high - low,
        "none": none,
        "points": points,
        "import": current,
    }
