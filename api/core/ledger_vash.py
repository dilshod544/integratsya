def _span(records: List[Dict[str, Any]], key: str) -> Tuple[Optional[date], Optional[date]]:
    days = [r[key] for r in records if r.get(key)]
    if not days:
        return None, None
    return min(days), max(days)


def _save_batch(kind: str, table: str, columns: Tuple[str, ...], records: List[Dict[str, Any]], filename: Optional[str], date_key: str) -> Dict[str, Any]:
    ensure_schema()
    date_from, date_to = _span(records, date_key)
    with connect() as conn:
        imp = start_import(conn, kind, filename, len(records), date_from, date_to)
        saved_columns = columns + ("import_id",)
        with conn.cursor() as cur:
            cur.executemany(
                f"INSERT INTO {table} ({', '.join(saved_columns)}) VALUES ({', '.join(['%s'] * len(saved_columns))})",
                [tuple(r.get(c) for c in columns) + (imp["id"],) for r in records],
            )
    return imp


