def _iso_date(value: Any) -> Optional[str]:
    if value is None:
        return None
    return value.isoformat() if hasattr(value, "isoformat") else str(value)[:10]


def is_uzs(code: Optional[str]) -> bool:
    return str(code or "").strip().upper().replace("Ў", "У") in _UZS or str(code or "").strip() in _UZS


def _currency_label(code: Optional[str]) -> str:
    raw = str(code or "").strip()
    meta = CURRENCY_META.get(raw)
    if meta:
        return f"{meta['code']} · {raw}"
    if is_uzs(raw):
        return "UZS"
    return raw or "—"


def _branch_names() -> Dict[str, Dict[str, Any]]:
    with connect() as conn:
        rows = conn.execute(
            "SELECT local_code, region, address FROM branches WHERE local_code IS NOT NULL"
        ).fetchall()
    out = {}
    for r in rows:
        code = str(r["local_code"]).strip()
        out[code] = {"name": str(r["address"] or "").split(".", 1)[0].strip(), "region": r.get("region")}
        out.setdefault(code.lstrip("0"), out[code])
    return out


