def _norm_header(value: Any) -> str:
    if value is None:
        return ""
    s = str(value).strip().lower().replace("ё", "е")
    s = s.replace("ў", "у").replace("қ", "к").replace("ғ", "г").replace("ҳ", "х")
    return re.sub(r"[\s_\-./\\()|+]+", "", s)


def _text(value: Any) -> Optional[str]:
    if value is None:
        return None
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    s = str(value).strip()
    return s or None


def _amount(value: Any) -> Optional[float]:
    if value is None or value == "":
        return None
    if isinstance(value, (int, float)):
        return float(value)
    s = str(value).strip().replace("\u00a0", "").replace(" ", "").replace(",", ".")
    s = re.sub(r"[^\d.\-]", "", s)
    if not s or s in ("-", ".", "-."):
        return None
    try:
        return float(s)
    except ValueError:
        return None


def _as_date(value: Any) -> Optional[date]:
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        try:
            from openpyxl.utils.datetime import from_excel
            parsed = from_excel(value)
            return parsed.date() if isinstance(parsed, datetime) else parsed
        except Exception:
            return None
    s = str(value).strip()
    slash = re.fullmatch(r"(\d{1,2})/(\d{1,2})/(\d{4})", s)
    if slash:
        a, b, year = int(slash.group(1)), int(slash.group(2)), int(slash.group(3))
        # 9/14/2026 va 9/2/2026 — oy/kun (bank hisoboti). 14/9/2026 — kun/oy.
        if a > 12 and 1 <= b <= 12:
            month, day = b, a
        elif 1 <= a <= 12:
            month, day = a, b
        else:
            return None
        try:
            return date(year, month, day)
        except ValueError:
            return None
    for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%d/%m/%Y", "%Y/%m/%d", "%d-%m-%Y"):
        try:
            return datetime.strptime(s[:10], fmt).date()
        except ValueError:
            continue
    return None


def _find_header(ws, aliases: Dict[str, str], required: Tuple[str, ...]) -> Tuple[int, Dict[str, int]]:
    for ridx, row in enumerate(ws.iter_rows(max_row=25, values_only=True), start=1):
        found: Dict[str, int] = {}
        for cidx, cell in enumerate(row):
            field = aliases.get(_norm_header(cell))
            if field and field not in found:
                found[field] = cidx
        if all(name in found for name in required):
            return ridx, found
    missing = ", ".join(required)
    raise ValueError(f"В листе «{ws.title}» не найдена шапка. Нужны колонки: {missing}")


def _iter_sheets(path: str | Path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    try:
        yield from wb.worksheets
    finally:
        wb.close()


def parse_branch_ledger_xlsx(path: str | Path) -> Dict[str, Any]:
    records: List[Dict[str, Any]] = []
    errors: List[Dict[str, Any]] = []
    header_row = None
    for ws in _iter_sheets(path):
        try:
            header_row, cols = _find_header(ws, _LEDGER_ALIASES, _LEDGER_REQUIRED)
        except ValueError:
            continue
        for ridx, row in enumerate(ws.iter_rows(min_row=header_row + 1, values_only=True), start=header_row + 1):
            if not row or all(c is None or str(c).strip() == "" for c in row):
                continue
            branch_id = _text(row[cols["branch_id"]])
            oper_day = _as_date(row[cols["oper_day"]])
            if not branch_id or oper_day is None:
                errors.append({"sheet": ws.title, "row": ridx, "error": "нет branch_id или oper_day"})
                continue
            records.append({
                "oper_day": oper_day,
                "coa_code": _text(row[cols["coa_code"]]),
                "code": _text(row[cols["code"]]),
                "code_currency": _text(row[cols["code_currency"]]),
                "acc_id": _text(row[cols["acc_id"]]),
                "branch_id": branch_id,
                "saldo_out": _amount(row[cols["saldo_out"]]),
            })
        break
    if header_row is None:
        raise ValueError(
            "Не найден отчёт остатков. Нужны колонки: oper_day, coa_code, code, "
            "code_currency, acc_id, branch_id, saldo_out"
        )
    if not records:
        raise ValueError("В файле нет строк с branch_id и oper_day")
    return {"records": records, "errors": errors, "header_row": header_row}


